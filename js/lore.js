// Кельтский «календарь деревьев» (Роберт Грейвс, 1948; современная конструкция, не древняя)
const CELTIC = [
  ['Берёза', 1224, 120], ['Рябина', 121, 217], ['Ясень', 218, 317],
  ['Ольха', 318, 414], ['Ива', 415, 512], ['Боярышник', 513, 609],
  ['Дуб', 610, 707], ['Падуб', 708, 804], ['Лещина', 805, 901],
  ['Виноградная лоза', 902, 929], ['Плющ', 930, 1027],
  ['Тростник', 1028, 1124], ['Бузина', 1125, 1223],
];

export function celticOf(month, day) {
  const md = month * 100 + day;
  for (const [name, a, b] of CELTIC) {
    if (a <= b ? md >= a && md <= b : md >= a || md <= b) return name;
  }
  return null;
}

