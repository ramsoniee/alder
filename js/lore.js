// Диапазон месяцев [from, to] включительно, с переходом через год
export function range(from, to) {
  const out = [];
  let m = from;
  for (let i = 0; i < 12; i++) {
    out.push(m);
    if (m === to) break;
    m = m === 12 ? 1 : m + 1;
  }
  return out;
}

