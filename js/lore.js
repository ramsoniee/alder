export function signOf(month, day) {
  const md = month * 100 + day;
  let found = SIGNS[0]; // Козерог с 22.12 по 31.12 и до 19.01
  for (const s of SIGNS) if (md >= s[2]) found = s;
  if (md < 120) found = SIGNS[0];
  return { name: found[0], symbol: found[1], planet: found[3] };
}

